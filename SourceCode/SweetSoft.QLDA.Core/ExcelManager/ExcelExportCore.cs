        private byte[] GenerateWorkbook(IEnumerable<WorksheetRequest> worksheetRequests, Action<int> onRowProcessed)
        {
            using (var package = new ExcelPackage())
            {
                var workbook = package.Workbook;
                var usedNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

                foreach (var request in worksheetRequests)
                {
                    if (request == null)
                    {
                        continue;
                    }

                    var options = EnsureOptions(request.Options);
                    ApplyWorkbookProperties(package, options);

                    var sheetName = GetUniqueSheetName(workbook, request.SheetName);
                    sheetName = EnsureUniqueWorksheetName(sheetName, usedNames);
                    usedNames.Add(sheetName);

                    var worksheet = workbook.Worksheets.Add(sheetName);

                    ApplyProtection(package, worksheet, options);

                    var headerLines = request.HeaderLines ?? new List<HeaderLine>();
                    WriteWorksheet(worksheet, request.Table, request.Rows, headerLines, options, onRowProcessed);
                }

                return package.GetAsByteArray();
            }
        }

        private void WriteWorksheet(ExcelWorksheet worksheet, DataTable table, IEnumerable<DataRow> rows, IList<HeaderLine> headerLines, ExcelExportOptions options, Action<int> onRowProcessed)
        {
            var effectiveRows = rows?.ToList() ?? table?.Rows.Cast<DataRow>().ToList() ?? new List<DataRow>();
            var displayColumns = ResolveDisplayColumns(table, options);
            int columnCount = Math.Max(1, displayColumns.Count);

            var originalHeaderRows = options.HeaderRows;
            options.HeaderRows = headerLines?.ToList();

            int row = 1;

            if (options.LogoImageBytes != null)
            {
                row = options.IsLogoCenter ? AddLogoCenter(worksheet, options) : AddLogo(worksheet, options);
                if (row == 0)
                {
                    row = 1;
                }
            }

            row = AddHeaders(worksheet, options, columnCount, row);

            int headerRowIndex = AddColumnHeaders(worksheet, displayColumns, row);
            if (options.IsFixedHeader)
            {
                worksheet.View.FreezePanes(headerRowIndex + 1, 1);
            }

            options.HeaderRows = originalHeaderRows;

            WriteDataRows(worksheet, table, effectiveRows, headerRowIndex, options, displayColumns, onRowProcessed);

            ApplyMergeCells(worksheet, options);
            ApplyGrouping(worksheet, options);
            ///

            ///
            AddCharts(worksheet, table, headerRowIndex, options);

            if (options.MasterDetailOptions == null)
            {
                ApplyColumnStyles(worksheet, table, headerRowIndex, options);
            }

            AdjustColumnWidth(worksheet, options, displayColumns);
            worksheet.View.ShowGridLines = options.ShowGridLines;
        }

