        }

        private int AddLogo(ExcelWorksheet worksheet, ExcelExportOptions options)
        {
            if (options.LogoImageBytes == null)
            {
                return 0;
            }

            var picture = worksheet.Drawings.AddPicture("Logo", new MemoryStream(options.LogoImageBytes), options.ImageType);
            picture.SetPosition(0, 0, 0, 0);
            picture.SetSize(options.LogoWidth, options.LogoHeight);

            int headerRowCount = options.HeaderRows?.Count ?? 1;

            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Merge = true;
            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Style.Border.BorderAround(ExcelBorderStyle.None);
            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Style.VerticalAlignment = ExcelVerticalAlignment.Center;

            return 1;
        }

        private int AddLogoCenter(ExcelWorksheet worksheet, ExcelExportOptions options)
        {
            if (options.LogoImageBytes == null)
            {
                return 0;
            }

            int headerRowCount = options.HeaderRows?.Count ?? 1;

            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Merge = true;
            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Style.Border.BorderAround(ExcelBorderStyle.None);
            worksheet.Cells[1, 1, headerRowCount, options.LogoCols].Style.VerticalAlignment = ExcelVerticalAlignment.Center;

            double totalHeightPoints = 0;
            for (int i = 1; i <= headerRowCount; i++)
            {
                totalHeightPoints += worksheet.Row(i).Height > 0 ? worksheet.Row(i).Height : worksheet.DefaultRowHeight;
            }

            double totalHeightPixels = totalHeightPoints * 1.555;
            double totalWidthPixels = 0;
            for (int i = 1; i <= options.LogoCols; i++)
            {
                double colWidth = worksheet.Column(i).Width > 0 ? worksheet.Column(i).Width : worksheet.DefaultColWidth;
                totalWidthPixels += colWidth * 7.5;
            }

            int offsetY = Math.Max((int)(totalHeightPixels - options.LogoHeight) / 2, 0);
            int offsetX = Math.Max((int)(totalWidthPixels - options.LogoWidth) / 2, 0);

            var picture = worksheet.Drawings.AddPicture("Logo", new MemoryStream(options.LogoImageBytes), options.ImageType);
            picture.SetPosition(0, Math.Max(offsetY, 0), 0, Math.Max(offsetX, 0));
            picture.SetSize(options.LogoWidth, options.LogoHeight);
            return 1;
        }

        private int AddMasterRow(ExcelWorksheet worksheet, DataRow row, int rowIdx, List<ColumnDisplayInfo> displayColumns, ExcelExportOptions options, Color backgroundColor, int rowIndex)
        {
            int columnCount = displayColumns.Count;
            bool hasMasterDetailOptions = options.MasterDetailOptions != null;

            for (int column = 0; column < columnCount; column++)
            {
                var columnInfo = displayColumns[column];
                string columnName = columnInfo.ColumnName;
                var cell = worksheet.Cells[rowIdx, column + 1];
                object value = row[columnName];

                SetCellValue(cell, value, columnName, options);

                if (hasMasterDetailOptions)
                {
                    ApplyMasterRowStyle(cell, options.MasterDetailOptions);
                }
                else
                {
                    ApplyCellStyle(cell, columnName, value, options, backgroundColor, rowIndex);
                }
            }

            return rowIdx + 1;
        }

        private int AddDetailRows(ExcelWorksheet worksheet, DataRow masterRow, int startRowIdx, List<ColumnDisplayInfo> displayColumns, ExcelExportOptions options)
        {
            if (options.MasterDetailOptions == null)
            {
                return startRowIdx;
            }

            var detailOptions = options.MasterDetailOptions;
            int currentRowIdx = startRowIdx;

            if (detailOptions.DetailDataTable == null || detailOptions.DetailColumns == null || detailOptions.DetailColumns.Count == 0)
            {
                return currentRowIdx;
            }

            object masterKeyValue = masterRow[detailOptions.MasterKeyColumn];
            if (masterKeyValue == null)
            {
                return currentRowIdx;
            }

            var detailRows = detailOptions.DetailDataTable.AsEnumerable()
                .Where(detailRow => detailRow[detailOptions.DetailForeignKeyColumn]?.ToString() == masterKeyValue.ToString())
                .ToList();

            if (!detailRows.Any())
            {
                return currentRowIdx;
            }

            if (detailOptions.ShowDetailHeaders)
            {
                currentRowIdx = AddDetailHeader(worksheet, currentRowIdx, displayColumns, detailOptions);
            }

            foreach (var detailRow in detailRows)
            {
                currentRowIdx = AddDetailRow(worksheet, detailRow, currentRowIdx, displayColumns, detailOptions);
            }

            return currentRowIdx;
        }

        private int AddDetailHeader(ExcelWorksheet worksheet, int rowIdx, List<ColumnDisplayInfo> displayColumns, MasterDetailOptions detailOptions)
        {
            if (detailOptions.DetailColumns == null)
            {
                return rowIdx;
            }

            int startCol = detailOptions.DetailIndentLevel + 1;

            for (int i = 0; i < detailOptions.DetailColumns.Count; i++)
            {
                string columnName = detailOptions.DetailColumns[i];
                var cell = worksheet.Cells[rowIdx, startCol + i];

                string displayName = detailOptions.DetailColumnNames != null && detailOptions.DetailColumnNames.ContainsKey(columnName)
                    ? detailOptions.DetailColumnNames[columnName]
                    : columnName;

                int span = 1;
                if (detailOptions.DetailHeaderMergeRightSpans != null && detailOptions.DetailHeaderMergeRightSpans.TryGetValue(columnName, out var mergeSpan) && mergeSpan > 1)
                {
                    span = mergeSpan;
                    var mergeRange = worksheet.Cells[rowIdx, startCol + i, rowIdx, startCol + i + span - 1];
                    mergeRange.Merge = true;
                    mergeRange.Value = displayName;

                    if (detailOptions.DetailHeaderStyle != null)
                    {
                        ApplyStyle(mergeRange, detailOptions.DetailHeaderStyle);
                    }
                    else
                    {
                        mergeRange.Style.Font.Bold = true;
                        mergeRange.Style.Fill.PatternType = ExcelFillStyle.Solid;
                        mergeRange.Style.Fill.BackgroundColor.SetColor(Color.LightGray);
                    }

                    mergeRange.Style.Border.Top.Style = ExcelBorderStyle.Thin;
                    mergeRange.Style.Border.Left.Style = ExcelBorderStyle.Thin;
                    mergeRange.Style.Border.Right.Style = ExcelBorderStyle.Thin;
                    mergeRange.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
                    mergeRange.Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;
                    mergeRange.Style.VerticalAlignment = ExcelVerticalAlignment.Center;

                    i += span - 1;
                }
                else
                {
                    cell.Value = displayName;

                    if (detailOptions.DetailHeaderStyle != null)
                    {
                        ApplyStyle(cell, detailOptions.DetailHeaderStyle);
                    }
                    else
                    {
                        cell.Style.Font.Bold = true;
                        cell.Style.Fill.PatternType = ExcelFillStyle.Solid;
                        cell.Style.Fill.BackgroundColor.SetColor(Color.LightGray);
                    }

                    cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
                    cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
                    cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
                    cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
                    cell.Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;
                    cell.Style.VerticalAlignment = ExcelVerticalAlignment.Center;
                }
            }

            return rowIdx + 1;
        }

        private int AddDetailRow(ExcelWorksheet worksheet, DataRow detailRow, int rowIdx, List<ColumnDisplayInfo> displayColumns, MasterDetailOptions detailOptions)
        {
            if (detailOptions.DetailColumns == null)
            {
                return rowIdx;
            }

            int startCol = detailOptions.DetailIndentLevel + 1;

            for (int i = 0; i < detailOptions.DetailColumns.Count; i++)
            {
                if (i >= detailOptions.DetailColumns.Count)
                {
                    break;
                }

                string columnName = detailOptions.DetailColumns[i];
                var cell = worksheet.Cells[rowIdx, startCol + i];
                object value = detailRow[columnName];

                SetDetailCellValue(cell, value, columnName, detailOptions);
                int skip = ApplyDetailColumnProperties(cell, columnName, detailOptions);
                ApplyDetailCellStyle(cell, columnName, detailOptions);

                cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
                cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
                cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
                cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
                i += skip;
            }

            return rowIdx + 1;
        }

        private static string ToExcelMultiline(string input)
        {
            try
            {
                if (string.IsNullOrWhiteSpace(input))
                {
                    return string.Empty;
                }

                var parts = input.Split(new[] { '|' }, StringSplitOptions.RemoveEmptyEntries);
                return string.Join(Environment.NewLine, parts.Select(x => x.Trim()));
            }
            catch
            {
                return input;
            }
        }

        private void SetCellValue(ExcelRange cell, object val, string colName, ExcelExportOptions options)
        {
            if (options.DecryptColumns != null && options.DecryptColumns.Contains(colName))
            {
                cell.Value = SQLEncryption.Decrypt(val);
            }
            else if (options.EnumMappings != null && options.EnumMappings.TryGetValue(colName, out var enumType))
            {
                cell.Value = EnumHelpers.GetERenderText(enumType, val);
            }
            else if (val is DateTime dateTimeValue)
            {
                cell.Value = FormatHelpers.ConvertDateTimeToStringByLanguage(dateTimeValue, false, null);
            }
            else
            {
                var mapping = options.ConditionalMappingTexts?.FirstOrDefault(mp => mp.ColumnName == colName);
                if (mapping != null)
                {
                    string value = val?.ToString();
                    string mappedText = null;

                    if (!string.IsNullOrEmpty(value) && mapping.ValueMappings.TryGetValue(value, out var staticMapped))
                    {
                        mappedText = staticMapped;
                    }
                    else if (mapping.ResolveFromDb != null)
                    {
                        mappedText = mapping.ResolveFromDb(val);
                    }

                    cell.Value = mappedText ?? mapping.DefaultText ?? ToExcelMultiline(val?.ToString());
                }
                else
                {
                    cell.Value = ToExcelMultiline(val?.ToString());
                }
            }
        }

        private void SetDetailCellValue(ExcelRange cell, object val, string colName, MasterDetailOptions detailOptions)
        {
            if (val is DateTime dateTimeValue)
            {
                cell.Value = FormatHelpers.ConvertDateTimeToStringByLanguage(dateTimeValue, false, null);
            }
            else
            {
                var mapping = detailOptions.ConditionalMappingTexts?.FirstOrDefault(mp => mp.ColumnName == colName);
                if (mapping != null)
                {
                    string value = val?.ToString();
                    string mappedText = null;

                    if (!string.IsNullOrEmpty(value) && mapping.ValueMappings.TryGetValue(value, out var staticMapped))
                    {
                        mappedText = staticMapped;
                    }
                    else if (mapping.ResolveFromDb != null)
                    {
                        mappedText = mapping.ResolveFromDb(val);
                    }

                    cell.Value = mappedText ?? mapping.DefaultText ?? ToExcelMultiline(val?.ToString());
                }
                else
                {
                    cell.Value = ToExcelMultiline(val?.ToString());
                }
            }

            if (detailOptions.DetailNumberFormats != null && detailOptions.DetailNumberFormats.TryGetValue(colName, out var format))
