            }
        }

        private void ApplyDetailCellStyle(ExcelRange cell, string colName, MasterDetailOptions detailOptions)
        {
            cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;

            if (detailOptions.DetailRowStyle != null)
            {
                ApplyStyle(cell, detailOptions.DetailRowStyle);
            }

            if (detailOptions.DetailColumnStyles != null && detailOptions.DetailColumnStyles.ContainsKey(colName))
            {
                ApplyStyle(cell, detailOptions.DetailColumnStyles[colName]);
            }
        }

        private int ApplyDetailColumnProperties(ExcelRange cell, string colName, MasterDetailOptions detailOptions)
        {
            Color? backgroundColor = null;

            if (detailOptions.DetailColumnBackgroundColors != null && detailOptions.DetailColumnBackgroundColors.TryGetValue(colName, out var color))
            {
                backgroundColor = color;
                cell.Style.Fill.PatternType = ExcelFillStyle.Solid;
                cell.Style.Fill.BackgroundColor.SetColor(color);
            }

            if (detailOptions.DetailColumnTextColors != null && detailOptions.DetailColumnTextColors.TryGetValue(colName, out var textColor))
            {
                cell.Style.Font.Color.SetColor(textColor);
            }

            if (detailOptions.DetailColumnBold != null && detailOptions.DetailColumnBold.TryGetValue(colName, out var bold))
            {
                cell.Style.Font.Bold = bold;
            }

            if (detailOptions.DetailColumnAlignments != null && detailOptions.DetailColumnAlignments.TryGetValue(colName, out var alignment))
            {
                cell.Style.HorizontalAlignment = alignment;
            }

            cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;

            int skipRight = 0;
            if (detailOptions.DetailColumnMergeRightSpans != null && detailOptions.DetailColumnMergeRightSpans.TryGetValue(colName, out var span) && span > 1)
            {
                var worksheet = cell.Worksheet;
                int row = cell.Start.Row;
                int column = cell.Start.Column;

                var range = worksheet.Cells[row, column, row, column + span - 1];
                range.Merge = true;
                range.Value = cell.Value;
                range.Style.WrapText = true;
                range.Style.VerticalAlignment = ExcelVerticalAlignment.Center;
                range.Style.HorizontalAlignment = cell.Style.HorizontalAlignment;
                range.Style.Font.Bold = cell.Style.Font.Bold;

                if (!string.IsNullOrEmpty(cell.Style.Font.Color.Rgb))
                {
                    range.Style.Font.Color.SetColor(ColorTranslator.FromHtml("#" + cell.Style.Font.Color.Rgb));
                }

                if (backgroundColor.HasValue)
                {
                    range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                    range.Style.Fill.BackgroundColor.SetColor(backgroundColor.Value);
                }

                range.Style.Border.Top.Style = ExcelBorderStyle.Thin;
                range.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
                range.Style.Border.Left.Style = ExcelBorderStyle.Thin;
                range.Style.Border.Right.Style = ExcelBorderStyle.Thin;

                skipRight = span - 1;
            }

            return skipRight;
        }

        private void ApplyMasterRowStyle(ExcelRange cell, MasterDetailOptions detailOptions)
        {
            cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;

            if (detailOptions.MasterRowStyle != null)
            {
                ApplyStyle(cell, detailOptions.MasterRowStyle);
            }
            else
            {
                cell.Style.Fill.PatternType = ExcelFillStyle.Solid;
                cell.Style.Fill.BackgroundColor.SetColor(detailOptions.MasterRowBackgroundColor);
                cell.Style.Font.Color.SetColor(detailOptions.MasterRowTextColor);
                cell.Style.Font.Bold = detailOptions.MasterRowBold;
            }
        }

        private void ApplyCellStyle(ExcelRange cell, string colName, object val, ExcelExportOptions options, Color backgroundColor, int rowIndex)
        {
            if (options.WrapTextColumns != null && options.WrapTextColumns.Contains(colName))
            {
                cell.Style.WrapText = true;
                cell.Worksheet.Row(cell.Start.Row).CustomHeight = false;
            }

            cell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
            cell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;

            if (options.EnableZebraStripe)
            {
                cell.Style.Fill.PatternType = ExcelFillStyle.Solid;
                cell.Style.Fill.BackgroundColor.SetColor(backgroundColor);
            }

            var conditionalFormat = options.ConditionalFormats?.FirstOrDefault(format => format.ColumnName == colName);
            if (conditionalFormat?.Condition?.Invoke(val) == true)
            {
                cell.Style.Font.Color.SetColor(Color.Red);
                cell.Style.Font.Bold = true;
            }
        }

        private void AddGrandTotalRow(ExcelWorksheet worksheet, int rowIdx, List<ColumnDisplayInfo> displayColumns, ExcelExportOptions options, Dictionary<string, decimal> grandTotals, int firstSumCol, int columnCount)
        {
            for (int column = 0; column < columnCount; column++)
            {
                var cell = worksheet.Cells[rowIdx, column + 1];
                ApplyStyle(cell, options.GrandTotalStyle);
            }

            if (firstSumCol > 0)
            {
                var titleCell = worksheet.Cells[rowIdx, 1, rowIdx, firstSumCol];
                titleCell.Merge = true;
                titleCell.Value = "Grand Total";
                ApplyStyle(titleCell, options.GrandTotalStyle);
            }

            if (options.SumColumns == null || options.SumColumns.Count == 0)
            {
                return;
            }

            foreach (var columnInfo in displayColumns)
            {
                if (!options.SumColumns.Contains(columnInfo.ColumnName))
                {
                    continue;
                }

                var cell = worksheet.Cells[rowIdx, displayColumns.IndexOf(columnInfo) + 1];
                cell.Value = grandTotals[columnInfo.ColumnName];
                ApplyStyle(cell, options.GrandTotalStyle);
            }
        }

        private void AddGroupSummary(ExcelWorksheet worksheet, int rowIdx, List<DataRow> rows, List<ColumnDisplayInfo> displayColumns, ExcelExportOptions options, int firstSumCol)
        {
            int columnCount = displayColumns.Count;

            for (int column = 0; column < columnCount; column++)
            {
                var cell = worksheet.Cells[rowIdx, column + 1];
                ApplyStyle(cell, options.GroupSummaryStyle);
            }

            if (firstSumCol > 0)
            {
                var titleCell = worksheet.Cells[rowIdx, 1, rowIdx, firstSumCol];
                titleCell.Merge = true;
                titleCell.Value = "Group Total";
                ApplyStyle(titleCell, options.GroupSummaryStyle);
            }

            if (options.SumColumns == null || options.SumColumns.Count == 0)
            {
                return;
            }

            foreach (var columnInfo in displayColumns)
            {
                if (!options.SumColumns.Contains(columnInfo.ColumnName))
                {
                    continue;
                }

                decimal sum = rows.Sum(row => decimal.TryParse(row[columnInfo.ColumnName]?.ToString(), out var value) ? value : 0);
                var cell = worksheet.Cells[rowIdx, displayColumns.IndexOf(columnInfo) + 1];
                cell.Value = sum;
                ApplyStyle(cell, options.GroupSummaryStyle);
            }
        }

        private void ApplyStyle(ExcelRange cell, ExcelStyle style)
        {
            if (cell == null || style == null)
