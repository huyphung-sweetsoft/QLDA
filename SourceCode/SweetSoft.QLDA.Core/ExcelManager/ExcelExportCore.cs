        }

        private void ApplyProtection(ExcelPackage package, ExcelWorksheet worksheet, ExcelExportOptions options)
        {
            if (options?.ExcelProtections == null)
            {
                return;
            }

            if (options.ExcelProtections.ProtectWorkbookStructure)
            {
                package.Workbook.Protection.SetPassword(options.ExcelProtections.Password);
                package.Workbook.Protection.LockStructure = true;
            }

            if (options.ExcelProtections.ProtectWorksheet)
            {
                worksheet.Protection.SetPassword(options.ExcelProtections.Password);
                worksheet.Protection.IsProtected = true;
                worksheet.Protection.AllowSelectLockedCells = options.ExcelProtections.AllowSelectLockedCells;
                worksheet.Protection.AllowSelectUnlockedCells = options.ExcelProtections.AllowSelectUnlockedCells;
                worksheet.Protection.AllowFormatCells = options.ExcelProtections.AllowFormatCells;
                worksheet.Protection.AllowDeleteColumns = options.ExcelProtections.AllowDeleteColumns;
                worksheet.Protection.AllowInsertRows = options.ExcelProtections.AllowInsertRows;
                worksheet.Protection.AllowSort = options.ExcelProtections.AllowSort;
            }
        }

        private string GetUniqueSheetName(ExcelWorkbook workbook, string requestedName)
        {
            string sheetName = string.IsNullOrWhiteSpace(requestedName) ? "Sheet" : requestedName;
            sheetName = sheetName.Length > 31 ? sheetName.Substring(0, 31) : sheetName;
            sheetName = Regex.Replace(sheetName, @"[:\\/?*\[\]]", "_");

            int suffix = 1;
            string uniqueName = sheetName;
            while (workbook.Worksheets.Any(w => string.Equals(w.Name, uniqueName, StringComparison.OrdinalIgnoreCase)))
            {
                uniqueName = $"{sheetName}_{suffix++}";
            }

            return uniqueName;
        }

        private string EnsureUniqueWorksheetName(string sheetName, ISet<string> usedNames)
        {
            string uniqueName = sheetName;
            int suffix = 1;
            while (usedNames.Contains(uniqueName))
            {
                uniqueName = $"{sheetName}_{suffix++}";
            }

            return uniqueName;
        }

        private List<ColumnDisplayInfo> ResolveDisplayColumns(DataTable table, ExcelExportOptions options)
        {
            options = EnsureOptions(options);

            var displayColumns = new List<ColumnDisplayInfo>();
            var showColumns = new List<string>();

            if (options.ShowColumns != null && options.ShowColumns.Any())
            {
                showColumns = options.ShowColumns
                    .Where(columnName => table == null || table.Columns.Contains(columnName))
                    .ToList();
            }
            else if (table != null)
            {
                showColumns = table.Columns.Cast<DataColumn>().Select(column => column.ColumnName).ToList();
            }

            if (table == null && showColumns.Count == 0 && options.ColumnNames != null && options.ShowColumns != null)
            {
                showColumns = options.ColumnNames.Select((_, index) => options.ShowColumns.ElementAtOrDefault(index)).Where(name => !string.IsNullOrEmpty(name)).ToList();
            }

            for (int i = 0; i < showColumns.Count; i++)
            {
                string columnName = showColumns[i];
                string displayName = options.ColumnNames != null && options.ColumnNames.Count > i
                    ? options.ColumnNames[i]
                    : GetDisplayNameFromColumn(columnName);

                displayColumns.Add(new ColumnDisplayInfo
                {
                    ColumnName = columnName,
                    DisplayName = displayName
                });
            }

            if (displayColumns.Count == 0 && table != null)
            {
                displayColumns.AddRange(table.Columns.Cast<DataColumn>().Select(column => new ColumnDisplayInfo
                {
                    ColumnName = column.ColumnName,
                    DisplayName = GetDisplayNameFromColumn(column.ColumnName)
                }));
            }

            return displayColumns;
        }

        private int AddHeaders(ExcelWorksheet worksheet, ExcelExportOptions options, int colCount, int startRow)
        {
            if (options.HeaderRows == null || options.HeaderRows.Count == 0)
            {
                return startRow;
            }

            int currentRow = startRow;
            int startCol = 1;

            foreach (var header in options.HeaderRows)
            {
                var cell = worksheet.Cells[currentRow, startCol, currentRow, colCount];
                cell.Merge = true;
                cell.Value = header.Text;

                if (header.FontSize.HasValue)
                {
                    cell.Style.Font.Size = header.FontSize.Value;
                }

                if (header.Bold.HasValue)
                {
                    cell.Style.Font.Bold = header.Bold.Value;
                }

                if (header.FontColor.HasValue)
                {
                    cell.Style.Font.Color.SetColor(header.FontColor.Value);
                }

                cell.Style.HorizontalAlignment = header.HorizontalAlignment ?? ExcelHorizontalAlignment.Left;
                cell.Style.VerticalAlignment = ExcelVerticalAlignment.Center;

                currentRow++;
            }

            return currentRow;
        }

        private int AddColumnHeaders(ExcelWorksheet worksheet, IList<ColumnDisplayInfo> columns, int row)
        {
            for (int columnIndex = 0; columnIndex < columns.Count; columnIndex++)
            {
                var headerCell = worksheet.Cells[row, columnIndex + 1];
                headerCell.Value = columns[columnIndex].DisplayName;
                headerCell.Style.Font.Bold = true;
                headerCell.Style.Font.Color.SetColor(Color.White);
                headerCell.Style.Font.Size = 14;
                headerCell.Style.Fill.PatternType = ExcelFillStyle.Solid;
                headerCell.Style.Fill.BackgroundColor.SetColor(DefaultHeaderColor);
                headerCell.Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;
                headerCell.Style.VerticalAlignment = ExcelVerticalAlignment.Center;
                headerCell.Style.Border.Top.Style = ExcelBorderStyle.Thin;
                headerCell.Style.Border.Bottom.Style = ExcelBorderStyle.Thin;
                headerCell.Style.Border.Left.Style = ExcelBorderStyle.Thin;
                headerCell.Style.Border.Right.Style = ExcelBorderStyle.Thin;
            }

            return row;
        }

        private void WriteDataRows(ExcelWorksheet worksheet, DataTable table, IList<DataRow> rows, int headerRowIndex, ExcelExportOptions options, List<ColumnDisplayInfo> displayColumns, Action<int> onRowProcessed)
        {
            if (rows == null)
            {
                return;
            }

            int rowIdx = headerRowIndex + 1;
            int processed = 0;
            int columnCount = displayColumns.Count;
            bool hasSumColumns = options.SumColumns != null && options.SumColumns.Any();
            var grandTotals = hasSumColumns
                ? options.SumColumns.ToDictionary(column => column, _ => 0m)
                : new Dictionary<string, decimal>();

            string lastGroupValue = null;
            var groupRows = new List<DataRow>();
            int firstSumColumn = GetFirstSumColumnIndex(displayColumns.ToList(), options);

            for (int index = 0; index < rows.Count; index++)
            {
                var dataRow = rows[index];
                string currentGroup = !string.IsNullOrEmpty(options.GroupByColumn) ? dataRow[options.GroupByColumn]?.ToString() : null;

                if (!string.IsNullOrEmpty(options.GroupByColumn) && lastGroupValue != null && !string.Equals(lastGroupValue, currentGroup, StringComparison.Ordinal))
                {
                    AddGroupSummary(worksheet, rowIdx, groupRows, displayColumns.ToList(), options, firstSumColumn);
                    rowIdx++;
                    groupRows.Clear();
                }

                groupRows.Add(dataRow);
                lastGroupValue = currentGroup;

                Color backgroundColor = index % 2 == 0 ? options.EvenRowColor : options.OddRowColor;
                rowIdx = AddMasterRow(worksheet, dataRow, rowIdx, displayColumns, options, backgroundColor, index);

                if (options.MasterDetailOptions != null)
                {
                    rowIdx = AddDetailRows(worksheet, dataRow, rowIdx, displayColumns, options);
                }

                if (hasSumColumns)
                {
                    foreach (var columnInfo in displayColumns)
                    {
                        if (!options.SumColumns.Contains(columnInfo.ColumnName))
                        {
                            continue;
                        }

                        object value = dataRow[columnInfo.ColumnName];
                        if (decimal.TryParse(value?.ToString(), out decimal parsed))
                        {
                            grandTotals[columnInfo.ColumnName] += parsed;
                        }
                    }
                }

                processed++;
                onRowProcessed?.Invoke(processed);
            }

            if (!string.IsNullOrEmpty(options.GroupByColumn) && groupRows.Any())
            {
                AddGroupSummary(worksheet, rowIdx, groupRows, displayColumns, options, firstSumColumn);
                rowIdx++;
            }

            if (options.ShowGrandTotal && hasSumColumns)
            {
                AddGrandTotalRow(worksheet, rowIdx, displayColumns, options, grandTotals, firstSumColumn, columnCount);
            }
        }

        private void AdjustColumnWidth(ExcelWorksheet worksheet, ExcelExportOptions options, IList<ColumnDisplayInfo> displayColumns)
        {
            if (displayColumns == null || displayColumns.Count == 0)
            {
                return;
            }

            int columnCount = displayColumns.Count;

            if (options.ColumnWidths != null && options.ColumnWidths.Count > 0)
            {
                for (int index = 0; index < columnCount; index++)
                {
                    var columnInfo = displayColumns[index];
                    if (options.ColumnWidths.TryGetValue(columnInfo.ColumnName, out double width))
                    {
                        worksheet.Column(index + 1).Width = width;
                    }
                    else
                    {
                        worksheet.Column(index + 1).AutoFit(20, 120);
                    }
                }
            }
            else if (worksheet.Dimension != null)
            {
                worksheet.Cells[1, 1, worksheet.Dimension.End.Row, columnCount].AutoFitColumns();
            }
        }

        private Action<ExcelRange> CreateDateStyle()
        {
            return range =>
            {
                range.Style.Numberformat.Format = "dd-mmm-yyyy";
                range.Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;
            };
        }

        private Action<ExcelRange> CreateCurrencyStyle()
        {
            return range =>
            {
                range.Style.Numberformat.Format = "#,##0.##";
                range.Style.HorizontalAlignment = ExcelHorizontalAlignment.Right;
            };
        }

