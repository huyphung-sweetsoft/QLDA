        private List<HeaderLine> CreateSheetHeaderLines(IEnumerable<HeaderLine> baseHeaderLines, int rowCount, bool includeRowCount)
        {
            var headers = CloneHeaderLines(baseHeaderLines);
            if (includeRowCount)
            {
                headers.Add(new HeaderLine { Text = $"Tổng số dòng: {rowCount}", FontSize = 12 });
            }

            return headers;
        }

        private List<HeaderLine> CloneHeaderLines(IEnumerable<HeaderLine> headers)
        {
            if (headers == null)
            {
                return new List<HeaderLine>();
            }

            return headers
                .Select(header => new HeaderLine
                {
                    Text = header.Text,
                    FontSize = header.FontSize,
                    Bold = header.Bold,
                    FontColor = header.FontColor,
                    HorizontalAlignment = header.HorizontalAlignment
                })
                .ToList();
        }

        private void ApplyWorkbookProperties(ExcelPackage package, ExcelExportOptions options)
        {
            if (options?.ExcelProperties == null)
            {
                return;
            }

            var props = package.Workbook.Properties;
            props.Title = options.ExcelProperties.Title;
            props.Subject = options.ExcelProperties.Subject;
            props.Author = options.ExcelProperties.Author;
            props.Keywords = options.ExcelProperties.Keywords;
            props.Comments = options.ExcelProperties.Comments;
            props.Company = options.ExcelProperties.Company;
