        public byte[] ExportExcel(DataTable dt, ExcelExportOptions options, Action<int> onRowProcessed = null)
        {
            if (dt == null)
                dt = new DataTable();
            options = EnsureOptions(options);

            var headerLines = CreateSheetHeaderLines(CloneHeaderLines(options.HeaderRows), dt.Rows.Count, includeRowCount: true);

            var worksheets = new List<WorksheetRequest>
            {
                new WorksheetRequest
                {
                    SheetName = options.SheetName,
                    Table = dt,
                    Rows = dt.Rows.Cast<DataRow>(),
                    Options = options,
                    HeaderLines = headerLines
                }
            };

            return GenerateWorkbook(worksheets, onRowProcessed);
        }

