            cell.Style.Border = style.Border;
            cell.Style.Fill = style.Fill;
            cell.Style.Font = style.Font;
            cell.Style.HorizontalAlignment = style.HorizontalAlignment;
            cell.Style.Numberformat = style.Numberformat;
        }

        private void ApplyStyle(ExcelRange cell, ExcelStyleOptions style)
