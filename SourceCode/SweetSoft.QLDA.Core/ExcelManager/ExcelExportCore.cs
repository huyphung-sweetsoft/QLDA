        }

        private void ApplyColumnStyles(ExcelWorksheet worksheet, DataTable table, int headerRowIndex, ExcelExportOptions options)
        {
            if (options?.ColumnStyles == null || table == null)
            {
                return;
            }

            foreach (var kvp in options.ColumnStyles)
            {
                int columnIndex = table.Columns.IndexOf(kvp.Key);
                if (columnIndex < 0)
                {
                    continue;
                }

                var range = worksheet.Cells[headerRowIndex + 1, columnIndex + 1, headerRowIndex + table.Rows.Count, columnIndex + 1];
                kvp.Value?.Invoke(range);
            }
        }

        private void ApplyMergeCells(ExcelWorksheet worksheet, ExcelExportOptions options)
        {
            if (options?.MergeCells == null)
            {
                return;
            }

            foreach (var mergeCell in options.MergeCells)
            {
                worksheet.Cells[mergeCell.FromRow, mergeCell.FromCol, mergeCell.ToRow, mergeCell.ToCol].Merge = true;
                worksheet.Cells[mergeCell.FromRow, mergeCell.FromCol].Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;
                worksheet.Cells[mergeCell.FromRow, mergeCell.FromCol].Style.VerticalAlignment = ExcelVerticalAlignment.Center;
            }
        }

        private void ApplyGrouping(ExcelWorksheet worksheet, ExcelExportOptions options)
        {
            if (options?.GroupRowRanges != null)
            {
                foreach (var row in options.GroupRowRanges)
                {
                    for (int i = 1; i <= 3; i++)
                    {
                        worksheet.Row(row + i).OutlineLevel = 1;
                        worksheet.Row(row + i).Collapsed = true;
                    }
                }
            }

            if (options?.GroupColumnRanges != null)
            {
                foreach (var column in options.GroupColumnRanges)
                {
                    for (int i = 1; i <= 2; i++)
                    {
                        worksheet.Column(column + i).OutlineLevel = 1;
                        worksheet.Column(column + i).Collapsed = true;
                    }
                }
            }
        }

        private void AddCharts(ExcelWorksheet worksheet, DataTable table, int headerRowIndex, ExcelExportOptions options)
        {
            if (table == null || options == null)
            {
                return;
            }

            int chartOffsetY = 0;
            int dataRow = 1;

            ExcelWorksheet dataSheet = worksheet;
            if (options.UseHiddenDataSheet)
            {
                dataSheet = worksheet.Workbook.Worksheets.FirstOrDefault(sheet => sheet.Name == "__Data")
                            ?? worksheet.Workbook.Worksheets.Add("__Data");

                for (int i = 0; i < table.Rows.Count; i++)
                {
                    for (int j = 0; j < table.Columns.Count; j++)
                    {
                        dataSheet.Cells[i + 2, j + 1].Value = table.Rows[i][j];
                        dataSheet.Cells[1, j + 1].Value = table.Columns[j].ColumnName;
                    }
                }

                dataSheet.Hidden = eWorkSheetHidden.VeryHidden;
            }

            if (options.GroupedChart != null)
            {
                int groupColumnIndex = table.Columns.IndexOf(options.GroupedChart.GroupByColumn);
                int categoryColumnIndex = table.Columns.IndexOf(options.GroupedChart.CategoryColumn);
                int valueColumnIndex = table.Columns.IndexOf(options.GroupedChart.ValueColumn);

                if (groupColumnIndex >= 0 && categoryColumnIndex >= 0 && valueColumnIndex >= 0)
                {
                    var groups = table.AsEnumerable().GroupBy(row => row[groupColumnIndex] ?? 0);
                    foreach (var group in groups)
                    {
                        var groupList = group.ToList();
                        int groupRowStart = dataRow + 1;

                        if (options.UseHiddenDataSheet)
                        {
                            for (int i = 0; i < groupList.Count; i++)
                            {
                                for (int j = 0; j < table.Columns.Count; j++)
                                {
                                    dataSheet.Cells[groupRowStart + i, j + 1].Value = groupList[i][j];
                                }
                            }
                        }

                        var chart = worksheet.Drawings.AddChart($"chart_{group.Key}", options.GroupedChart.ChartType);
                        chart.Title.Text = $"{options.GroupedChart.ValueColumn} - {group.Key}";
                        chart.SetPosition(headerRowIndex + table.Rows.Count + chartOffsetY + 3, 0, 0, 0);
                        chart.SetSize(800, 400);

                        chart.Series.Add(
                            dataSheet.Cells[groupRowStart, valueColumnIndex + 1, groupRowStart + groupList.Count - 1, valueColumnIndex + 1],
                            dataSheet.Cells[groupRowStart, categoryColumnIndex + 1, groupRowStart + groupList.Count - 1, categoryColumnIndex + 1]);

                        chartOffsetY += groupList.Count + 15;
                        dataRow = groupRowStart + groupList.Count;
                    }
                }
            }

            if (options.Charts != null && options.Charts.Any())
            {
                foreach (var chartConfig in options.Charts)
                {
                    int categoryColumnIndex = table.Columns.IndexOf(chartConfig.CategoryColumn);
                    int valueColumnIndex = table.Columns.IndexOf(chartConfig.ValueColumn);

                    if (categoryColumnIndex < 0 || valueColumnIndex < 0)
                    {
                        continue;
                    }

                    var drawing = worksheet.Drawings.AddChart($"chart_{chartConfig.Title}", chartConfig.ChartType);
                    drawing.Title.Text = chartConfig.Title;
                    drawing.SetPosition(headerRowIndex + table.Rows.Count + chartOffsetY + 3, 0, 0, 0);
                    drawing.SetSize(800, 400);

                    drawing.Series.Add(
                        dataSheet.Cells[2, valueColumnIndex + 1, table.Rows.Count + 1, valueColumnIndex + 1],
                        dataSheet.Cells[2, categoryColumnIndex + 1, table.Rows.Count + 1, categoryColumnIndex + 1]);

                    chartOffsetY += table.Rows.Count + 5;
                }
            }
        }

        private int GetFirstSumColumnIndex(List<ColumnDisplayInfo> displayColumns, ExcelExportOptions options)
        {
            if (displayColumns == null || options?.SumColumns == null)
            {
                return displayColumns?.Count > 0 ? displayColumns.Count - 1 : 0;
            }

            foreach (var column in displayColumns.Select((info, index) => new { info.ColumnName, index }))
            {
                if (options.SumColumns.Contains(column.ColumnName))
                {
                    return column.index;
                }
            }

            return displayColumns.Count > 0 ? displayColumns.Count - 1 : 0;
        }

        private string GetDisplayNameFromColumn(string columnName)
