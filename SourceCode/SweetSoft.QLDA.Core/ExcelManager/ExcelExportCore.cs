        public byte[] ExportToExcelMultipleSheets(Dictionary<string, DataTable> sheetData, string subject, ExcelExportOptions options, Action<int> onRowProcessed = null)
        {
            if (sheetData == null || sheetData.Count == 0)
            {
                return null;
            }

            var context = CreateExportContext(subject);
            options = EnsureOptions(options);
            ApplyDefaultDocumentOptions(options, context);

            var baseHeaderLines = CloneHeaderLines(options.HeaderRows);

            var worksheets = sheetData
                .Where(entry => entry.Value != null)
                .Select(entry => new WorksheetRequest
                {
                    SheetName = entry.Key,
                    Table = entry.Value,
                    Rows = entry.Value.Rows.Cast<DataRow>(),
                    Options = options,
                    HeaderLines = CreateSheetHeaderLines(baseHeaderLines, entry.Value.Rows.Count, includeRowCount: true)
                })
                .ToList();

            return GenerateWorkbook(worksheets, onRowProcessed);
        }

        public byte[] ExportToExcelFromPagedTable(DataTable table, string subject, int maxRowsPerSheet, string baseSheetName, ExcelExportOptions options, Action<int> onRowProcessed = null)
        {
            if (table == null || table.Rows.Count == 0)
            {
                return null;
            }

            var context = CreateExportContext(subject);
            options = EnsureOptions(options);
            ApplyDefaultDocumentOptions(options, context);

            var baseHeaderLines = CloneHeaderLines(options.HeaderRows);

            int totalRows = table.Rows.Count;
            int sheetCount = (int)Math.Ceiling(totalRows / (double)maxRowsPerSheet);
            var worksheets = new List<WorksheetRequest>();

            for (int sheetIndex = 0; sheetIndex < sheetCount; sheetIndex++)
            {
                int startRowIndex = sheetIndex * maxRowsPerSheet;
                int length = Math.Min(maxRowsPerSheet, totalRows - startRowIndex);
                var rows = table.AsEnumerable().Skip(startRowIndex).Take(length).ToList();

                worksheets.Add(new WorksheetRequest
                {
                    SheetName = sheetIndex == 0 ? baseSheetName : $"{baseSheetName}_{sheetIndex + 1}",
                    Table = table,
                    Rows = rows,
                    Options = options,
                    HeaderLines = CreateSheetHeaderLines(baseHeaderLines, rows.Count, includeRowCount: true)
                });
            }

            return GenerateWorkbook(worksheets, onRowProcessed);
        }

        public byte[] ExportToExcelMultipleSheets(List<ExcelSheetItem> sheets, string subject, Action<int> onRowProcessed = null)
        {
            if (sheets == null || sheets.Count == 0)
            {
                return null;
            }

            string appVersion = Assembly.GetExecutingAssembly().GetName().Version.ToString();

            foreach (var sheet in sheets.Where(sheet => sheet?.Options != null))
            {
                var options = EnsureOptions(sheet.Options);
                options.EvenRowColor = Color.White;
                options.OddRowColor = Color.FromArgb(240, 240, 240);

                options.ExcelProperties = sheet.Options.ExcelProperties ?? new ExcelDocumentProperties();
                options.ExcelProperties.Title = subject;
                options.ExcelProperties.Subject = subject;
                options.ExcelProperties.Comments = $"Generated by PM Quản Lý Dự Án {appVersion}";
            }

            var worksheets = sheets
                .Where(sheet => sheet?.Table != null)
                .Select(sheet => new WorksheetRequest
                {
                    SheetName = sheet.SheetName,
                    Table = sheet.Table,
                    Rows = sheet.Table.Rows.Cast<DataRow>(),
                    Options = EnsureOptions(sheet.Options),
                    HeaderLines = CloneHeaderLines(sheet.Options?.HeaderRows)
                })
                .ToList();

            return GenerateWorkbook(worksheets, onRowProcessed);
        }

